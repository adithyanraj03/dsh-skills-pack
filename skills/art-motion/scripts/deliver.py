"""deliver.py — one command to deliver: measure the gates → red means no film; green/yellow copies the film and writes delivery notes, with the facts written by the script.

    uv run deliver.py <film.mp4> --out output/ [--spec clip.json | --project <engine>] [--qa <qa output dir>] [--root <project dir>]
                      [--sub-band 0.15] [--vertical auto|yes|no] [--allow-blue-purple "reason"]
    uv run deliver.py --verify output/delivery-notes.md       # check whether the facts section was edited

Does three things:
  1. Runs film_gate.py from the same directory. Red: no copy, no notes — prints the reason and the fix, exit code 2.
  2. Green or yellow: copies the film to --out and writes --out/delivery-notes.md. The facts section is entirely script-written:
     duration, resolution, fps, audio track, file fingerprint; every gate metric and its light; the worst 30-second window;
     whether qa ran and with what result (reads qa.json in the qa output dir; writes "not run" if absent);
     whether an independent review exists (are there <project dir>/review/*.md files; lists names; if none, writes "no reviewer dispatched").
  3. The facts section ends with a fingerprint. The maker only fills the "Production notes" section with subjective text
     (which grammar/style was used, why each yellow item is acceptable, the six-failure-mode self-check) and never edits the facts;
     edits are caught by --verify.

Conventions:
  - qa output dir: --qa wins; otherwise same defaults as qa.py — --spec → <spec's dir>/qa, --project → <engine's parent>/qa.
  - project dir: --root wins; otherwise --project's parent; otherwise the spec's dir; otherwise the film's dir.
  - The reviewer (an agent or person not involved in making the film) writes conclusions as <project dir>/review/<any name>.md.
    The script only checks the files exist; it does not read them and never concludes on the reviewer's behalf.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import film_gate  # noqa: E402

for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass

DOC = "delivery-notes.md"
START = "<!-- deliver.py facts: begin. This section is generated by the script — do not edit; deliver.py --verify catches edits -->"
END_RE = re.compile(r"<!-- deliver\.py facts: end sha256=([0-9a-f]{64}) -->")
LIGHT = {"red": "RED", "yellow": "YELLOW", "green": "GREEN", "--": ""}


def probe(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries",
                                   "stream=codec_type,codec_name,width,height,avg_frame_rate:format=duration",
                                   "-of", "json", str(path)])
    j = json.loads(out)
    v = next(s for s in j["streams"] if s.get("codec_type") == "video")
    a = [s for s in j["streams"] if s.get("codec_type") == "audio"]
    num, _, den = (v.get("avg_frame_rate") or "0/1").partition("/")
    fps = float(num) / float(den or 1) if float(den or 1) else 0.0
    return {"duration": float(j["format"].get("duration") or 0), "width": v["width"], "height": v["height"],
            "fps": round(fps, 3), "vcodec": v.get("codec_name"), "audio": a[0].get("codec_name") if a else None}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def stamp(p):
    return datetime.datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M:%S")


def qa_facts(qa_dir, spec):
    """Read qa.py's output. Returns fact lines (list)."""
    if qa_dir is None:
        return ["- not run (no --spec / --project / --qa given, nowhere to look for qa output)"]
    f = qa_dir / "qa.json"
    if not f.is_file():
        return [f"- not run ({f} does not exist)"]
    try:
        r = json.loads(f.read_text(encoding='utf-8'))
    except (ValueError, OSError) as e:
        return [f"- qa.json unreadable: {f} ({type(e).__name__}); counted as not run"]
    segs = r.get("segments", [])
    det = sum(1 for s in segs if s.get("deterministic"))
    spikes = sum(len(s.get("spikes_at_lt", [])) for s in segs)
    cams = sum(len(s.get("camera_events_lt", [])) for s in segs)
    framing = sum(len(s.get("framing", [])) for s in segs)
    errs = r.get("page_errors", [])
    L = [f"- ran: `{f}` (written {stamp(f)})",
         f"- page errors: {len(errs)}" + (" (qa judged FAIL)" if errs else ""),
         f"- determinism: {det}/{len(segs)} segments pixel-identical",
         f"- jumps: {spikes}" + (f"; plus {cams} camera events (monotone smooth pushes/pans under 2 s, not counted as jumps)" if "camera_events_lt" in (segs[0] if segs else {}) else ""),
         f"- framing leads: {framing} (half-cut text, overlapping text, graphics in the subtitle band, near-blank; these mean 'go look at this frame', they are not errors)"]
    for s in segs:
        L.append(f"  - {s.get('id')}: motion {s.get('motion_pct')}%, still frame pairs {s.get('still_pairs_pct')}%, "
                 f"jumps {len(s.get('spikes_at_lt', []))}, {s.get('ms_mean')}/{s.get('ms_max')} ms/frame")
    if spec is not None and r.get("spec") and Path(r["spec"]).resolve() != spec.resolve():
        L.append(f"- note: this qa.json measured a different spec ({r['spec']}), not {spec}")
    if spec is not None and spec.is_file() and spec.stat().st_mtime > f.stat().st_mtime:
        L.append(f"- note: the spec changed after qa ran (spec written {stamp(spec)}); these qa results may be stale")
    return L


def review_facts(root):
    d = root / "review"
    files = sorted(p.name for p in d.glob("*.md")) if d.is_dir() else []
    if not files:
        return [f"- no reviewer dispatched (no .md files under `{d}`)"]
    return [f"- {len(files)} review record(s) (`{d}`): " + ", ".join(files),
            "- the script only confirms the files exist; it did not read them — the review conclusions are whatever the files say"]


def facts_block(src, dst, info, res, rows, qa_lines, rv_lines):
    ex = res["explain"]
    gl = res["gate_light"]
    L = ["## Facts (written by deliver.py)", "",
         f"- generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
         f"- film: `{dst.name}` (sha256 {sha256(dst)[:16]}; source `{src}`)",
         f"- duration {info['duration']:.2f}s | {info['width']}×{info['height']} | {info['fps']:g}fps | video {info['vcodec']} | "
         f"audio: {info['audio'] or 'none'}",
         "", "### Gate (film_gate)", "",
         f"- verdict: {LIGHT[gl]}. fast-motion frame share {res['fast_ratio']} (< 0.035 red, < 0.06 yellow)",
         f"- in one line: {ex['summary']}." + (" ".join(ex["why"]) + "." if ex["why"] else "")]
    if res.get("allow_blue_purple"):
        L.append(f"- maker declares the subject needs blue-purple (blue-purple gate downgraded to yellow): {res['allow_blue_purple']}; blue-purple ground {res['blue_purple_share']:.0%}")
    if ex["worst_window"]:
        w = ex["worst_window"]
        L.append(f"- worst {w['end_s'] - w['start_s']:.0f}s window: {w['start_s']:.0f}–{w['end_s']:.0f}s, fast-motion share {w['fast_ratio']}")
    if ex["fix"]:
        L.append(f"- how to fix: {ex['fix']}")
    L += ["", "| light | kind | metric | value |", "|---|---|---|---|"]
    for k, name, v, lv, gate, unit in rows:
        vs = "—" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))
        L.append(f"| {LIGHT[lv] or 'report only'} | {'gate' if gate else 'report'} | {name} | {vs}{unit} |")
    L += ["", "### qa", ""] + qa_lines + ["", "### Independent review", ""] + rv_lines
    return "\n".join(L) + "\n"


def write_doc(out, dst, facts, res):
    h = hashlib.sha256(facts.encode()).hexdigest()
    look = [t for _, t in res["explain"]["look"]]
    if res["lights"]["fast_ratio"] == "yellow":
        look.insert(0, f"gate yellow: fast-motion frame share {res['fast_ratio']} (yellow line 0.06)")
    tail = ["## Production notes (filled by the maker; write only in this section, leave the facts alone)", "",
            "- grammar / style used:",
            "- six failure modes, checked one by one:",
            "- yellow items, one by one (timecode + why this is acceptable): " + ("" if look else "no yellow items")]
    tail += [f"  - {t}:" for t in look]
    doc = f"# Delivery notes: {dst.name}\n\n{START}\n{facts}<!-- deliver.py facts: end sha256={h} -->\n\n" + "\n".join(tail) + "\n"
    (out / DOC).write_text(doc)
    return out / DOC


def verify(path):
    t = Path(path).read_text(encoding='utf-8')
    i = t.find(START)
    m = END_RE.search(t)
    if i < 0 or not m or m.start() < i:
        print(f"❌ {path}: facts begin/end markers missing (deleted, or this file was not written by deliver.py)"); return 3
    facts = t[i + len(START) + 1: m.start()]
    if hashlib.sha256(facts.encode()).hexdigest() != m.group(1):
        print(f"❌ {path}: the facts section was edited and no longer matches what deliver.py wrote. Rerun deliver.py to regenerate."); return 3
    print(f"✓ {path}: facts section matches what deliver.py wrote"); return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mp4", nargs="?")
    ap.add_argument("--out", help="delivery directory (e.g. output/)")
    ap.add_argument("--spec", help="parametric clip spec (used to find qa output: <spec's dir>/qa)")
    ap.add_argument("--project", help="engine directory (used to find qa output: <engine's parent>/qa)")
    ap.add_argument("--qa", help="qa output directory (when qa.py --out wrote elsewhere)")
    ap.add_argument("--root", help="project directory (look for review/*.md under it)")
    ap.add_argument("--sub-band", type=float, default=None, help="same as film_gate.py: fraction of the bottom subtitle band to mask")
    ap.add_argument("--vertical", default="auto", choices=["auto", "yes", "no"])
    ap.add_argument("--verify", metavar="delivery-notes.md", help="only check whether the facts section was edited")
    ap.add_argument("--allow-blue-purple", metavar="reason", default=None,
                    help="same as film_gate.py: when the subject itself needs blue-purple, give the reason; it goes into the facts section")
    a = ap.parse_args()
    if a.verify:
        sys.exit(verify(a.verify))
    if not a.mp4 or not a.out:
        ap.error("need the film and --out")
    src = Path(a.mp4).resolve()
    if not src.is_file():
        print(f"film not found: {src}", file=sys.stderr); sys.exit(1)
    if not shutil.which("ffmpeg") or not shutil.which("ffprobe"):
        print("ffmpeg/ffprobe required", file=sys.stderr); sys.exit(1)
    spec = Path(a.spec).resolve() if a.spec else None
    proj = Path(a.project).resolve() if a.project else None
    qa_dir = Path(a.qa).resolve() if a.qa else spec.parent / "qa" if spec else proj.parent / "qa" if proj else None
    root = Path(a.root).resolve() if a.root else proj.parent if proj else spec.parent if spec else src.parent

    try:
        info = probe(src)
        res, rows = film_gate.measure(str(src), sub_band=a.sub_band, vertical=a.vertical, allow_blue_purple=a.allow_blue_purple)
    except (subprocess.CalledProcessError, StopIteration, KeyError, RuntimeError, ValueError) as e:
        print(f"cannot read this film: {src} ({e})", file=sys.stderr); sys.exit(1)
    print("\n".join(film_gate.report_lines(res, rows)))
    ex = res["explain"]
    if res["verdict"] == "red":
        print(f"\n❌ RED — not delivered: {ex['summary']}." + (" ".join(ex["why"]) + "." if ex["why"] else ""))
        print("How to fix: " + ex["fix"])
        print(f"The film was not copied and {DOC} was not written. Re-render, then run deliver.py again.")
        sys.exit(2)

    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    dst = out / src.name
    if dst != src:
        shutil.copy2(src, dst)
    qa_lines, rv_lines = qa_facts(qa_dir, spec), review_facts(root)
    facts = facts_block(src, dst, info, res, rows, qa_lines, rv_lines)
    doc = write_doc(out, dst, facts, res)
    gl = res["gate_light"]
    print(f"\n{'✓ GREEN' if gl == 'green' else '⚠ YELLOW'}, delivered: {dst}")
    print(f"delivery notes: {doc} (facts written by the script; subjective text only in the Production notes section)")
    print("qa: " + qa_lines[0][2:])
    print("review: " + rv_lines[0][2:])
    if ex["look"]:
        print("yellow items need a timecode and reason each in the delivery notes: " + "; ".join(t for _, t in ex["look"]))
    sys.exit(0)


if __name__ == "__main__":
    main()
